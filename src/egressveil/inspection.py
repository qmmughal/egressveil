"""Request inspection pipeline: parse -> detect -> decide -> redact.

Pure and synchronous: no sockets, so it is easy to test and the gateway can
run it in a worker thread.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from dataclasses import dataclass, field
from enum import StrEnum
from typing import TYPE_CHECKING, Final
from urllib.parse import unquote_plus

from egressveil.detectors import build_detectors
from egressveil.policy import GatewayMode, PolicyAction
from egressveil.policy.engine import PolicyEngine, most_restrictive
from egressveil.providers.base import (
    OpaqueItem,
    ProviderAdapter,
    RouteKind,
    TextField,
    UninspectableError,
    parse_json_body,
    walk_body,
)

if TYPE_CHECKING:
    from egressveil.audit import AuditLogger
    from egressveil.config import AllowEntry, EgressVeilConfig
    from egressveil.detectors import Detector, Finding
    from egressveil.redactor import Redactor

__all__ = [
    "URL_LOCATION",
    "Inspector",
    "LocatedFinding",
    "Outcome",
    "Verdict",
    "detectors_from_config",
]

URL_LOCATION: Final = "$url"
_JSON_TYPES: Final = frozenset({"application/json"})


class Outcome(StrEnum):
    FORWARD = "forward"
    """Send the original bytes upstream unchanged."""
    REDACT = "redact"
    """Send the rewritten body upstream."""
    BLOCK = "block"
    """Send nothing upstream."""


@dataclass(frozen=True, slots=True)
class LocatedFinding:
    detector: str
    rule_id: str
    location: str
    action: PolicyAction
    digest: str
    escalated: bool = False
    """REDACT was raised to BLOCK because the location cannot be rewritten (URL)."""
    signed: bool = False
    """Found in provider-signed content; recorded only (see Inspector docs)."""

    def as_audit(self) -> dict[str, object]:
        out: dict[str, object] = {
            "detector": self.detector,
            "rule_id": self.rule_id,
            "location": self.location,
            "action": self.action.value,
            "digest": self.digest,
        }
        if self.escalated:
            out["escalated"] = True
        if self.signed:
            out["signed"] = True
        return out


@dataclass(slots=True)
class Verdict:
    outcome: Outcome
    body: bytes
    route: RouteKind
    findings: list[LocatedFinding] = field(default_factory=list)
    reason: str | None = None
    """Machine code for why a request was blocked or forwarded uninspected."""
    message: str | None = None
    """Human explanation. Contains locations and rule IDs only, never values."""
    opaque: list[OpaqueItem] = field(default_factory=list)
    inspected: bool = True


def detectors_from_config(config: EgressVeilConfig) -> list[Detector]:
    enabled = [name for name, d in config.detectors.items() if d.enabled]
    hostnames = config.detectors["internal_hostnames"]
    return build_detectors(
        enabled,
        internal_domains=hostnames.internal_domains,
        include_common_internal_suffixes=hostnames.include_common_internal_suffixes,
        include_private_ips=hostnames.include_private_ips,
    )


class Inspector:
    """Applies detectors and policy to requests.

    Signed content (e.g. Anthropic ``thinking`` blocks) carries a provider
    signature over its exact text: it was generated by the provider and cannot
    be altered by the client. Re-sending it discloses nothing new, and
    modifying or blocking it would only break or wedge the session, so findings
    there are recorded with action ``LOG_ONLY`` and ``signed: true``.
    """

    def __init__(
        self,
        *,
        detectors: Sequence[Detector],
        engine: PolicyEngine,
        redactor: Redactor,
        audit: AuditLogger,
        mode: GatewayMode,
        allow_opaque_content: bool,
        allow: Sequence[AllowEntry] = (),
    ) -> None:
        self._detectors = tuple(detectors)
        self._engine = engine
        self._redactor = redactor
        self._audit = audit
        self._strict = mode is GatewayMode.STRICT
        self._allow_opaque = allow_opaque_content
        self._allow = tuple(allow)

    @classmethod
    def from_config(
        cls, config: EgressVeilConfig, *, redactor: Redactor, audit: AuditLogger
    ) -> Inspector:
        return cls(
            detectors=detectors_from_config(config),
            engine=PolicyEngine(config.policy),
            redactor=redactor,
            audit=audit,
            mode=config.gateway.mode,
            allow_opaque_content=config.gateway.allow_opaque_content,
            allow=config.policy.allow,
        )

    # ------------------------------------------------------------------ text

    def scan_text(self, text: str) -> list[Finding]:
        findings: list[Finding] = []
        for detector in self._detectors:
            findings.extend(detector.scan(text))
        return findings

    def digest(self, value: str) -> str:
        return self._audit.digest(value)

    def is_allowed(self, finding: Finding, value: str, digest: str) -> bool:
        """True when a ``policy.allow`` entry suppresses this finding."""
        return any(e.matches(finding.detector, finding.rule_id, value, digest) for e in self._allow)

    def evaluate_text(self, text: str) -> list[tuple[Finding, PolicyAction, str]]:
        """Findings in ``text`` with their action and digest, after allowlist and ALLOW."""
        out: list[tuple[Finding, PolicyAction, str]] = []
        for f in self.scan_text(text):
            action = self.action_for(f)
            if action is PolicyAction.ALLOW:
                continue
            value = text[f.start : f.end]
            digest = self._audit.digest(value)
            if self.is_allowed(f, value, digest):
                continue
            out.append((f, action, digest))
        return out

    def action_for(self, finding: Finding) -> PolicyAction:
        return self._engine.action_for(finding)

    # ------------------------------------------------------------------ request

    def inspect_request(
        self,
        *,
        adapter: ProviderAdapter,
        method: str,
        path: str,
        query: str,
        content_type: str | None,
        content_encoding: str | None,
        body: bytes,
    ) -> Verdict:
        route = adapter.classify(method, path, has_body=bool(body))
        try:
            return self._inspect(adapter, route, query, content_type, content_encoding, body)
        except UninspectableError as exc:
            return self._uninspectable(route, body, exc.reason, exc.message)
        except Exception:  # a detector bug must never fail open in strict mode
            return self._uninspectable(
                route, body, "detector_error", "internal error while inspecting the request"
            )

    def _uninspectable(self, route: RouteKind, body: bytes, reason: str, message: str) -> Verdict:
        outcome, sent = (Outcome.BLOCK, b"") if self._strict else (Outcome.FORWARD, body)
        return Verdict(outcome, sent, route, reason=reason, message=message, inspected=False)

    def _inspect(
        self,
        adapter: ProviderAdapter,
        route: RouteKind,
        query: str,
        content_type: str | None,
        content_encoding: str | None,
        body: bytes,
    ) -> Verdict:
        if route is RouteKind.UNSUPPORTED:
            raise UninspectableError(
                "unsupported_route", "this API endpoint is not supported by EgressVeil"
            )

        located: list[LocatedFinding] = []
        if query:
            located.extend(self._scan_url(query))

        if route is RouteKind.BODYLESS:
            return self._decide(route, body, located, opaque=[])

        media_type = (content_type or "").split(";", 1)[0].strip().lower()
        if media_type not in _JSON_TYPES:
            raise UninspectableError(
                "unsupported_content_type", "request body must be application/json"
            )
        encoding = (content_encoding or "identity").strip().lower()
        if encoding != "identity":
            raise UninspectableError(
                "unsupported_content_encoding", "compressed request bodies are not supported"
            )

        document = parse_json_body(body)
        fields, opaque = walk_body(document, adapter.profile)
        if opaque and not self._allow_opaque and self._strict:
            where = ", ".join(o.location for o in opaque[:3])
            raise UninspectableError(
                "opaque_content",
                f"request contains content EgressVeil cannot inspect (e.g. images, audio or "
                f"files) at {where}; set gateway.allow_opaque_content: true to forward such "
                f"content",
            )

        to_redact: list[tuple[TextField, list[Finding]]] = []
        for text_field in fields:
            redactable: list[Finding] = []
            for f, action, digest in self.evaluate_text(text_field.text):
                signed = text_field.signed and action is not PolicyAction.LOG_ONLY
                if signed:
                    action = PolicyAction.LOG_ONLY
                located.append(
                    LocatedFinding(
                        f.detector, f.rule_id, text_field.location, action, digest, signed=signed
                    )
                )
                if action is PolicyAction.REDACT:
                    redactable.append(f)
            if redactable:
                to_redact.append((text_field, redactable))

        verdict = self._decide(route, body, located, opaque=opaque)
        if verdict.outcome is Outcome.REDACT:
            for text_field, findings in to_redact:
                text_field.replace(self._redactor.redact(text_field.text, findings))
            verdict.body = json.dumps(document, ensure_ascii=True, separators=(",", ":")).encode(
                "ascii"
            )
        return verdict

    def _scan_url(self, query: str) -> list[LocatedFinding]:
        decoded = unquote_plus(query)
        out: list[LocatedFinding] = []
        for f, action, digest in self.evaluate_text(decoded):
            # URLs cannot be rewritten safely, so REDACT escalates to BLOCK.
            escalated = action is PolicyAction.REDACT
            out.append(
                LocatedFinding(
                    f.detector,
                    f.rule_id,
                    URL_LOCATION,
                    PolicyAction.BLOCK if escalated else action,
                    digest,
                    escalated=escalated,
                )
            )
        return out

    def _decide(
        self,
        route: RouteKind,
        body: bytes,
        located: list[LocatedFinding],
        *,
        opaque: list[OpaqueItem],
    ) -> Verdict:
        action = most_restrictive(f.action for f in located)
        reason = "opaque_content_forwarded" if opaque else None
        if action is PolicyAction.BLOCK:
            blocking = [f for f in located if f.action is PolicyAction.BLOCK]
            shown = "; ".join(f"{f.detector}/{f.rule_id} at {f.location}" for f in blocking[:5])
            more = f" (+{len(blocking) - 5} more)" if len(blocking) > 5 else ""
            return Verdict(
                Outcome.BLOCK,
                b"",
                route,
                located,
                reason="policy",
                message=f"sensitive data detected: {shown}{more}",
                opaque=opaque,
            )
        outcome = Outcome.REDACT if action is PolicyAction.REDACT else Outcome.FORWARD
        return Verdict(outcome, body, route, located, reason=reason, opaque=opaque)
